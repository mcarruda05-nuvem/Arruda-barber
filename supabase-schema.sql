-- ARRUDA BARBER: banco compartilhado com autenticação
-- Execute este arquivo no SQL Editor do seu projeto Supabase.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null check (name in ('Felipe', 'Arruda')),
  created_at timestamptz not null default now()
);

create table if not exists public.movements (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('entrada', 'saida')),
  description text not null check (char_length(description) between 1 and 100),
  amount numeric(12,2) not null check (amount > 0),
  entry_date date not null,
  barber text not null check (barber in ('Felipe', 'Arruda')),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.movements enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles
for select to authenticated using (id = auth.uid());

drop policy if exists "movements_read_authenticated" on public.movements;
create policy "movements_read_authenticated" on public.movements
for select to authenticated using (true);

drop policy if exists "movements_insert_as_self" on public.movements;
create policy "movements_insert_as_self" on public.movements
for insert to authenticated with check (
  created_by = auth.uid()
  and barber = (select p.name from public.profiles p where p.id = auth.uid())
);

-- Os lançamentos são imutáveis nesta primeira versão: sem política de update/delete.
-- Somente usuários autenticados e com perfil podem consultar e inserir.
